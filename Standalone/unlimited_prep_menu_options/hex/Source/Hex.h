/*
 * Hex (standalone add-on, FE8U clean ROM). The card item and collection helpers (HexCards.c), the card table (HexCardTypes.c),
 * the item-name hooks (HexItem.c), the rules engine (HexCore.c, HexCore.h), the card art (HexArt.c), the Preparations row
 * (HexPrep.c) and the Hex screen (HexScreen.c). See ../README.md.
 *
 * HEX_CARD_ITEM must match HEX_CARD_ITEM in ../Installer.event, which writes the item row.
 * HEX_PREP_SLOT must match HEX_PREP_SLOT in ../Installer.event, which points the parent's extension slot at HexPrepRow.
 */
#pragma once

#include "global.h"
#include "HexCore.h"

/* Vanilla item slot used for cards (a "Dummy" item, see README). */
#define HEX_CARD_ITEM 0xC1

/* Preparations menu extension slot (0 to 7) of the Hex row. The row's key and state are 0x40 + HEX_PREP_SLOT. */
#define HEX_PREP_SLOT 0

#define HEX_CARD_TYPES 32

/* One row of gHexCardTypes (HexCardTypes.c). The card type is the uses byte of the card item word. */
struct HexCardType {
	u8 attack;
	u8 maxHp;
	u8 reach;	/* 6-bit mask, bit d = attacks in direction d (0 up-left, 1 up-right, 2 right, 3 down-right, 4 down-left, 5 left) */
	u8 tier;
	u8 starter;	/* copies handed out by HexCol_GiveStarters */
	u8 pid;		/* CHARACTER_* whose name and description the card shows */
};

extern const struct HexCardType gHexCardTypes[HEX_CARD_TYPES];

/* HexCards.c */
bool IsHexCardItem(int item);
int MakeHexCardItem(int type);
int HexCard_Type(int item);
int HexCard_NameId(int item);
int HexCard_DescId(int item);

int HexCol_Count(int type);
int HexCol_Total(void);
bool HexCol_GiveToConvoy(int type);
bool HexCol_TakeOne(int type);
void HexCol_GiveStarters(void);

/* HexItem.c: the GetItemName / GetItemDescId hooks (vanilla behaviour for every other item). */
char *HexItem_GetItemName(int item);
int HexItem_GetItemDescId(int item);

/*
 * Card art (HexArt.c). The UI tiles and palettes are 4bpp, 1D OBJ order, row-major; gHexPortraitKeep is the 32x32 portrait
 * mask (generated by Tools/hex/gen_hex_art.py in the repo).
 */
extern const u32 gHexFrameTiles[64][128];
extern const u32 gHexCardBackTiles[128];
extern const u32 gHexEmptyTiles[128];
extern const u32 gHexDigitTiles[11][8];
extern const u32 gHexDigitGreenTiles[11][8];
extern const u32 gHexScoreTiles[10][32];
extern const u32 gHexCursorTiles[2][32];
extern const u16 gHexFramePalRed[16];
extern const u16 gHexFramePalBlue[16];
extern const u32 gHexPortraitKeep[128];

/*
 * The Hex screen's match state (struct HexScreenState in HexScreen.c), 0x200 bytes of EWRAM at 0x0203C100 (RamAlloc.s).
 * Only used while the Hex screen is open.
 */
extern u8 gHexScreenState[];

/* HexScreen.c: the screen the Hex row starts (a blocking child of the Preparations menu, see HexPrep.c). */
struct ProcCmd;
extern const struct ProcCmd ProcScr_HexScreen[];
