#!/bin/bash
# Regenerate Kernel/Wizardry/BanimCodec/Source/BanimHuffArm.s from Tools/banim/huffdec.c (see that file).
# The code goes between _ARM_BanimHuff_CopyStart and _ARM_BanimHuff_CopyEnd; BanimCodec.c copies that span into IWRAM
# and BanimCodec.event checks that it fits.
set -e
cd "$(dirname "$0")/../.."
CC=${DEVKITARM:?run the devkitARM setup first}/bin/arm-none-eabi-gcc
OUT=Kernel/Wizardry/BanimCodec/Source/BanimHuffArm.s
TMP=$(mktemp)
$CC -S -Os -mcpu=arm7tdmi -marm -mthumb-interwork -fno-tree-loop-distribute-patterns -fno-ident \
	Tools/banim/huffdec.c -o "$TMP"
if grep -E '^\s(bl|blx|b)\s+[A-Za-z_]' "$TMP"; then
	echo "BanimHuff_DecodeArm calls out: it can't run from a copy" >&2
	exit 1
fi
if grep -E '^\s\.(section|data|bss)|\.rodata' "$TMP"; then
	echo "BanimHuff_DecodeArm has data of its own: it can't run from a copy" >&2
	exit 1
fi
{
	echo "@ Generated by Tools/banim/gen_huffdec_asm.sh from Tools/banim/huffdec.c. Do not edit."
	echo "@ $($CC --version | head -1)"
	echo "@ The code between the Copy labels runs from a copy in IWRAM (BanimCodec.c)."
	awk '
		/^BanimHuff_DecodeArm:/ { print "\t.global _ARM_BanimHuff_CopyStart"; print "_ARM_BanimHuff_CopyStart:" }
		/^\t\.size\tBanimHuff_DecodeArm/ { print; print "\t.global _ARM_BanimHuff_CopyEnd"; print "_ARM_BanimHuff_CopyEnd:"; next }
		/^\t\.(file|ident)/ { next }
		{ print }
	' "$TMP"
} > "$OUT"
rm -f "$TMP"
echo "wrote $OUT"
