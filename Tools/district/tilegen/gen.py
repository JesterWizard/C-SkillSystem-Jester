#!/usr/bin/env python3
"""Generate a district layout from a spec (see specs/ and README.md).

Usage:
  python3 Tools/district/tilegen/gen.py <spec.py> [--seeds N] [--seed S] [--out-dir DIR]
      [--write-layout PATH] [--check-layout PATH]

Per seed: Wave Function Collapse on natural terrain guided by the sketch, then the building
stamps and fixed tiles are pasted, then patch_repair re-solves small patches around bad joins,
then every door is checked for reachability from the gate. Seeds are ranked by
(unreachable doors, conflicts). The best three are written to DIR as <out>_<k>.json (debug
data, includes seed and conflicts), <out>_<k>.png (grid overlay) and <out>_<k>_clean.png.

--seed S runs only seed S. --write-layout PATH writes the best result as a layout JSON
(w, h, tileset, tiles) for Tools/district/district_map.py. --check-layout PATH compares the
best result's tiles with that layout file: prints MATCH (exit 0) or DIFF n tiles (exit 1).

DIR defaults to a build/ folder next to the spec. It holds a .gitignore of '*', so the
output is not tracked.
"""

import argparse
import json
import os
import runpy
import sys
import time
from itertools import zip_longest

from fe8map import load_map, render, render_grid, terrain, tileset
from pixedge import extend_model
from repair import patch_repair, total_conflicts
from rules import NATURAL, build_allowed, connected, water_tiles
from wfc import DIRS, WFC, train


def building_stamp(ts, src, mid, ddx, ddy, tx, ty, margin=1):
    """Cut the building whose door is at (ddx, ddy) in map mid (non-natural cells around the door) plus a ground margin."""
    if mid not in src:
        src[mid] = load_map(mid)
    SW, SH, ST = src[mid]
    tsrc = lambda x, y: terrain(ts, ST[y * SW + x]) or 0
    seen = {(ddx, ddy)}
    q = [(ddx, ddy)]
    while q:
        x, y = q.pop()
        for dx, dy in DIRS:
            n = (x + dx, y + dy)
            if n in seen or not (0 <= n[0] < SW and 0 <= n[1] < SH):
                continue
            if abs(n[0] - ddx) > 3 or n[1] > ddy or ddy - n[1] > 3:
                continue
            if tsrc(*n) in NATURAL:
                continue
            seen.add(n)
            q.append(n)
    x0 = max(0, min(p[0] for p in seen) - margin)
    x1 = min(SW - 1, max(p[0] for p in seen) + margin)
    y0 = max(0, min(p[1] for p in seen) - margin)
    y1 = min(SH - 1, max(p[1] for p in seen) + margin)
    dx0 = tx - (ddx - x0)
    dy0 = ty - (ddy - y0)
    return (mid, x0, y0, x1 - x0 + 1, y1 - y0 + 1, dx0, dy0)


def build_fixed(spec, ts, W, H):
    """Tiles that the WFC must not change: building stamps (cut from vanilla maps) and explicit tiles."""
    src = {}
    for b in spec.get('buildings', []):
        st = building_stamp(ts, src, *b[:5])
        print("building", b, "-> stamp", st, flush=True)
        spec['stamps'].append(st)
    fixed = {}
    for (mid, sx, sy, sw, sh, dx, dy) in spec['stamps']:
        if mid not in src:
            src[mid] = load_map(mid)
        SW, SH, ST = src[mid]
        for j in range(sh):
            for i in range(sw):
                if 0 <= dx + i < W and 0 <= dy + j < H:
                    fixed[(dy + j) * W + dx + i] = ST[(sy + j) * SW + sx + i]
    for (x, y), v in spec.get('tiles', {}).items():
        fixed[y * W + x] = v
    return fixed


def run_seed(spec, m, ts, W, H, fixed, allowed, seed):
    """One seed: base WFC, paste fixed tiles, patch repair. Returns (unreachable, conflicts, tiles) or None."""
    t0 = time.time()
    tf = lambda v: terrain(ts, v) or 0
    try:
        wts = dict(m[4])
        for v in wts:
            wts[v] = wts[v] * spec.get('terrain_weight', {}).get(tf(v), 1.0)
        base = WFC(W, H, m, allowed=allowed, seed=seed, weights=wts).run()
    except ValueError as e:
        print(seed, "base contradiction", e, flush=True)
        return None
    t = list(base)
    for i, v in fixed.items():
        t[i] = v
    t = patch_repair(t, W, H, m, fixed, allowed, seed=seed)
    conf = total_conflicts(t, W, H, m)
    bad = connected(W, H, t, tf, spec['start'], spec['reach'])
    print(seed, "conflicts", conf, "unreachable", bad, "time", round(time.time() - t0, 1), flush=True)
    return len(bad), conf, t


def write_outputs(spec, ts, W, H, best, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    gi = os.path.join(out_dir, ".gitignore")
    if not os.path.exists(gi):
        with open(gi, "w", encoding="utf-8") as f:
            f.write("# generated by Tools/district/tilegen/gen.py\n*\n")
    out = os.path.join(out_dir, spec['out'])
    for k, (nb, conf, seed, t) in enumerate(best[:3]):
        with open("%s_%d.json" % (out, k), "w", encoding="utf-8") as f:
            json.dump({"w": W, "h": H, "tileset": list(spec['tileset']), "tiles": t,
                       "seed": seed, "conflicts": conf}, f)
        render_grid(W, H, t, ts, "%s_%d.png" % (out, k), 2)
        render(W, H, t, ts, "%s_%d_clean.png" % (out, k), 2)
        print("wrote %s_%d.json (seed %d, unreachable %d, conflicts %d)" % (out, k, seed, nb, conf), flush=True)


def write_layout(spec, W, H, tiles, path):
    layout = {"w": W, "h": H, "tileset": list(spec['tileset']), "tiles": tiles}
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(layout, f)
        f.write("\n")
    print("wrote layout %s" % path, flush=True)


def check_layout(W, H, tiles, path):
    """Print MATCH or DIFF n tiles. Returns True when the tiles match."""
    with open(path, "r", encoding="utf-8") as f:
        lay = json.load(f)
    n = sum(1 for a, b in zip_longest(tiles, lay["tiles"]) if a != b)
    if (lay["w"], lay["h"]) != (W, H):
        print("DIFF %d tiles (size %dx%d vs layout %dx%d)" % (n, W, H, lay["w"], lay["h"]))
        return False
    if n == 0:
        print("MATCH")
        return True
    print("DIFF %d tiles" % n)
    return False


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate a district layout from a spec")
    ap.add_argument("spec", help="spec .py file with a SPEC dict")
    ap.add_argument("--seeds", type=int, default=4, help="try seeds 0..N-1 (default 4)")
    ap.add_argument("--seed", type=int, help="run only this seed")
    ap.add_argument("--out-dir", help="where to write outputs (default: build/ next to the spec)")
    ap.add_argument("--write-layout", metavar="PATH", help="write the best result as a layout JSON")
    ap.add_argument("--check-layout", metavar="PATH", help="compare the best result with a layout JSON")
    args = ap.parse_args(argv)

    spec = runpy.run_path(args.spec)['SPEC']
    W, H = spec['w'], spec['h']
    ts = tileset(*spec['tileset'])
    m = train(spec['train'])
    extend_model(m, ts, thresh=spec.get('thresh', 3.0), same_terrain_only=False, exclude=water_tiles(m[0], ts))
    sk = [list(r) for r in spec['sketch']]
    fixed = build_fixed(spec, ts, W, H)
    allowed, _ = build_allowed(m, ts, sk, W, H)

    seeds = [args.seed] if args.seed is not None else list(range(args.seeds))
    best = []
    for seed in seeds:
        r = run_seed(spec, m, ts, W, H, fixed, allowed, seed)
        if r is not None:
            best.append((r[0], r[1], seed, r[2]))
    best.sort(key=lambda r: (r[0], r[1]))
    if not best:
        print("no seed produced a result", file=sys.stderr)
        return 2

    out_dir = args.out_dir or os.path.join(os.path.dirname(os.path.abspath(args.spec)), "build")
    write_outputs(spec, ts, W, H, best, out_dir)
    nb, conf, seed, tiles = best[0]
    print("best: seed %d, unreachable %d, conflicts %d" % (seed, nb, conf), flush=True)
    if nb:
        print("warning: %d door(s) unreachable from the gate" % nb, file=sys.stderr)

    if args.write_layout:
        write_layout(spec, W, H, tiles, args.write_layout)
    if args.check_layout:
        return 0 if check_layout(W, H, tiles, args.check_layout) else 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
