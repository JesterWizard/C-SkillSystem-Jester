#!/bin/bash
# Regenerate Kernel/Wizardry/VoiceStream/Source/VoiceSynthArm.s from Tools/voice/vsynth.c (see that file).
# The code goes between _ARM_VoiceSynth_CopyStart and _ARM_VoiceSynth_CopyEnd; VoiceStream.c copies that span
# into IWRAM and checks that it fits.
set -e
cd "$(dirname "$0")/../.."
CC=${DEVKITARM:?run the devkitARM setup first}/bin/arm-none-eabi-gcc
OUT=Kernel/Wizardry/VoiceStream/Source/VoiceSynthArm.s
TMP=$(mktemp)
$CC -S -O2 -mcpu=arm7tdmi -marm -mthumb-interwork -fno-tree-loop-distribute-patterns -fno-ident \
	Tools/voice/vsynth.c -o "$TMP"
if grep -E '^\s(bl|blx|b)\s+[A-Za-z_]' "$TMP"; then
	echo "VoiceSynth_Frame calls out: it can't run from a copy" >&2
	exit 1
fi
{
	echo "@ Generated by Tools/voice/gen_synth_asm.sh from Tools/voice/vsynth.c. Do not edit."
	echo "@ $($CC --version | head -1)"
	echo "@ The code between the Copy labels runs from a copy in IWRAM (VoiceStream.c)."
	awk '
		/^VoiceSynth_Frame:/ { print "\t.global _ARM_VoiceSynth_CopyStart"; print "_ARM_VoiceSynth_CopyStart:" }
		/^\t\.size\tVoiceSynth_Frame/ { print; print "\t.global _ARM_VoiceSynth_CopyEnd"; print "_ARM_VoiceSynth_CopyEnd:"; next }
		/^\t\.(file|ident)/ { next }
		{ print }
	' "$TMP"
} > "$OUT"
rm -f "$TMP"
echo "wrote $OUT"
